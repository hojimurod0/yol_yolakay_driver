  @override
  Future<List<CityEntity>> getCities() async {
    await Future.delayed(const Duration(milliseconds: 200));
    return _cities;
  }

  @override
  Future<List<CityEntity>> getPopularCities() async {
    await Future.delayed(const Duration(milliseconds: 150));
    return _cities.where((c) => c.isPopular).toList();
  }

  @override
  Future<List<CityEntity>> searchCities(String query) async {
    await Future.delayed(const Duration(milliseconds: 100));
    if (query.trim().isEmpty) return _cities;
    final q = query.toLowerCase().trim();
    return _cities.where((c) {
      return c.nameUz.toLowerCase().contains(q) ||
          c.nameRu.toLowerCase().contains(q) ||
          c.nameEn.toLowerCase().contains(q) ||
          c.region.toLowerCase().contains(q);
    }).toList();
  }

  Future<CityEntity?> getCityById(String id) async {
    await Future.delayed(const Duration(milliseconds: 50));
    try {
      return _cities.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }
